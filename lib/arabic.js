// التطبيع العربي — الموضع الوحيد الذي يقرر متى يكون نصّان «نفس الكلمة».
//
// كان هذا المنطق يسكن في `agent/skills.js` ويخدم محفّز المهارات وحده، بينما
// `search_files` يقارن بـ`includes` الحرفية. والنتيجة مفارقة في تطبيق عربي:
// المحفّز يفهم أن «الاسبوع» هي «الأسبوع»، والبحث في ملفات المستخدم لا يفهم —
// فـ«شركه» لا تجد «شركة»، و«ملخص» لا تجد «ملخّص».
//
// ما يوحَّد ولماذا:
//   • التشكيل — يُكتب أحيانًا ويُترك أحيانًا، وهو أكثر مصادر الفشل الصامت.
//   • همزات الألف (أ إ آ ٱ ← ا) — لا أحد يلتزم بها في الكتابة اليومية.
//   • الألف المقصورة (ى ← ي) والتاء المربوطة (ة ← ه) — خلط شائع ومقبول.
//   • الهمزات على الكرسي (ؤ ئ ← ء).
//   • ما ليس حرفًا ولا رقمًا يصير فراغًا، والفراغات تُدمج.

const DIACRITICS = /[ً-ٰٟـ]/g;

/** يردّ صورةً مطبَّعة تصلح للمقارنة — لا للعرض */
function normalize(text) {
  return String(text || '')
    .replace(DIACRITICS, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/[ؤئ]/g, 'ء')
    .replace(/[^\p{L}\p{N}\s]/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

module.exports = { normalize, DIACRITICS };
